"""Build custom_components/ipixelcolorha/README.html from README.md.

The integration serves README.html from Home Assistant itself (see
async_setup in __init__.py), so the "Documentation" link on its integration
page works offline and needs no website. Run this after editing README.md:

    python tools/build_ipixelcolorha_readme.py

Needs the "markdown" package on the machine you run it on (not in Home
Assistant). The page records the SHA-256 of the README it was built from;
tests/ipixelcolorha/test_readme.py fails if README.html is out of date.
"""

from __future__ import annotations

import hashlib
import html
from pathlib import Path

import markdown

COMPONENT = Path(__file__).resolve().parents[1] / "custom_components" / "ipixelcolorha"
SOURCE = COMPONENT / "README.md"
TARGET = COMPONENT / "README.html"

STYLE = """
:root { color-scheme: light dark; --fg: #1c1c1c; --bg: #fafafa; --muted: #6b6b6b;
  --code: #eef0f2; --border: #d0d4d8; --link: #03a9f4; }
@media (prefers-color-scheme: dark) {
  :root { --fg: #e1e1e1; --bg: #111111; --muted: #9b9b9b; --code: #1f2328;
    --border: #3a3f44; --link: #4fc3f7; }
}
body { font: 16px/1.55 Roboto, "Segoe UI", system-ui, sans-serif; color: var(--fg);
  background: var(--bg); margin: 0; }
main { max-width: 52rem; margin: 0 auto; padding: 1.5rem 1.25rem 4rem; }
h1, h2, h3 { line-height: 1.25; margin: 2rem 0 0.75rem; }
h1 { margin-top: 0.5rem; }
h2 { border-bottom: 1px solid var(--border); padding-bottom: 0.3rem; }
a { color: var(--link); }
code { background: var(--code); border-radius: 4px; padding: 0.1em 0.35em;
  font: 0.9em/1.4 ui-monospace, Consolas, monospace; }
pre { background: var(--code); border-radius: 6px; padding: 0.9rem 1rem; overflow-x: auto; }
pre code { background: none; padding: 0; }
table { border-collapse: collapse; margin: 1rem 0; display: block; overflow-x: auto; }
th, td { border: 1px solid var(--border); padding: 0.4rem 0.6rem; text-align: left;
  vertical-align: top; }
th { background: var(--code); }
footer { color: var(--muted); font-size: 0.85rem; margin-top: 3rem; }
"""


def source_digest(text: str) -> str:
    """Return the digest README.html records for README.md's text."""
    return hashlib.sha256(text.replace("\r\n", "\n").encode("utf-8")).hexdigest()


def build() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    body = markdown.markdown(
        text,
        extensions=["tables", "fenced_code", "toc", "sane_lists"],
        extension_configs={"toc": {"permalink": False}},
        output_format="html",
    )
    title = text.splitlines()[0].lstrip("# ").strip() or "iPIXELcolorHA"
    return (
        "<!DOCTYPE html>\n"
        f"<!-- source-sha256: {source_digest(text)} -->\n"
        "<!-- Generated by tools/build_ipixelcolorha_readme.py; edit README.md instead. -->\n"
        '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{html.escape(title)} documentation</title>\n"
        f"<style>{STYLE}</style>\n</head>\n<body>\n<main>\n{body}\n"
        "<footer>Served by the iPIXELcolorHA integration from its own "
        "README.md.</footer>\n</main>\n</body>\n</html>\n"
    )


if __name__ == "__main__":
    TARGET.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET}")
